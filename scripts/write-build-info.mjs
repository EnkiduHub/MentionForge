#!/usr/bin/env node
/**
 * Stamps src/lib/build-info.ts with the current git short SHA and UTC time.
 * Invoked by wrangler `build.command` so `wrangler deploy` / `--dry-run` pick it up.
 */
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dest = join(root, "src/lib/build-info.ts");

function gitShortSha() {
  try {
    const sha = execSync("git rev-parse --short HEAD", {
      cwd: root,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
    return /^[0-9a-f]{4,40}$/i.test(sha) ? sha : null;
  } catch {
    return null;
  }
}

const sha = gitShortSha() ?? "dev";
const builtAt = sha === "dev" ? null : new Date().toISOString();

writeFileSync(
  dest,
  `/** Generated by scripts/write-build-info.mjs during wrangler deploy/dev. Default is local/dev. */
export const BUILD_SHA = ${JSON.stringify(sha)};
export const BUILD_AT: string | null = ${builtAt === null ? "null" : JSON.stringify(builtAt)};
`,
);
